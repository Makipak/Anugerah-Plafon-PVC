export type GaleriFotoSlug = (typeof galeriFotoKategori)[number]["slug"];
export type GaleriAssetId = `${(typeof galeriFotoKategori)[number]["prefix"]}-${string}`;

export function galeriAssetId(slug: GaleriFotoSlug, index: number): GaleriAssetId {
  const kategori = galeriFotoKategori.find((item) => item.slug === slug);
  if (!kategori) throw new Error(`Kategori galeri tidak dikenal: ${slug}`);
  return `${kategori.prefix}-${String(index + 1).padStart(2, "0")}`;
}

export function galeriFotoRatio(slug: GaleriFotoSlug, index: number): string {
  const kategori = galeriFotoKategori.find((item) => item.slug === slug);
  const ratio = kategori?.ratios[index];
  if (!ratio) throw new Error(`Rasio foto galeri tidak tersedia: ${slug}-${index + 1}`);
  return ratio;
}
